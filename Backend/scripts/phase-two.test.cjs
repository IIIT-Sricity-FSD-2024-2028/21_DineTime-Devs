const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),Module=require('node:module');
const root=path.resolve(__dirname,'..'),build=path.join(root,'dist');
const originalResolve=Module._resolveFilename;
Module._resolveFilename=function(request,parent,isMain,options){if(request.startsWith('src/'))request=path.join(build,request.slice(4));return originalResolve.call(this,request,parent,isMain,options);};
process.env.DINETIME_DB_PATH=path.join(fs.mkdtempSync(path.join(require('node:os').tmpdir(),'dinetime-phase-two-')),'test.sqlite');
const {NestFactory}=require('@nestjs/core'),{AppModule}=require(path.join(build,'app.module.js'));
let app,checks=0;
const pass=name=>{checks++;console.log('PASS '+name);};
const fails=(fn,status)=>assert.throws(fn,error=>error.getStatus?.()===status);
(async()=>{
  app=await NestFactory.createApplicationContext(AppModule,{logger:false,abortOnError:false});
  const get=(file,name)=>app.get(require(path.join(build,file))[name]);
  const reservations=get('modules/reservations/reservations.service.js','ReservationsService');
  const payments=get('modules/payments/payments.service.js','PaymentsService');
  const finance=get('modules/finance/finance.service.js','FinanceService');
  const timeslots=get('modules/timeslots/timeslots.service.js','TimeslotsService');
  const checkin=get('modules/checkin/checkin.service.js','CheckinService');
  const rr=get('repositories/reservation.repository.js','ReservationRepository');
  const pr=get('repositories/payment.repository.js','PaymentRepository');
  const sr=get('repositories/timeslot.repository.js','TimeSlotRepository');
  const tr=get('repositories/table.repository.js','TableRepository');
  const ar=get('repositories/tableslot.repository.js','TableSlotRepository');
  const rest=get('repositories/restaurant.repository.js','RestaurantRepository');
  const restaurant=rest.findAll()[0],tables=tr.findByRestaurantId(restaurant.id);
  const slot=sr.findByRestaurantId(restaurant.id).find(s=>Date.parse(s.slot_date+'T'+s.start_time+'+05:30')>Date.now()+86400000);
  const next=sr.findByRestaurantId(restaurant.id).find(s=>s.slot_date>slot.slot_date && s.start_time===slot.start_time);
  const book=(table=tables[0],chosen=slot)=>reservations.create({user_id:'din-1234',restaurant_id:restaurant.id,table_id:table.id,slot_id:chosen.id,guest_count:2});
  const pay=(booking,outcome='success')=>payments.create({reservation_id:booking.id,payment_method:'upi',transaction_ref:'CLIENT-SPOOF',amount:1,payment_status:'paid',demo_outcome:outcome});
  const booking=book();
  assert.ok(booking.hold_expires_at);assert.equal(timeslots.findOne(slot.id).locked,false);
  fails(()=>checkin.create({reservation_id:booking.id,staff_id:'rst-1234'}),400);
  fails(()=>timeslots.saveLayout(slot.id,{revision:0,tables:[{table_id:tables[0].id,capacity:3}]}),409);
  const decline=pay(booking,'failure');assert.equal(decline.payment_status,'failed');assert.equal(rr.findById(booking.id).confirmed_at,undefined);
  const payment=pr.findById(pay(booking).id);assert.equal(payment.mode,'demo');assert.ok(payment.amount>1);assert.notEqual(payment.transaction_ref,'CLIENT-SPOOF');
  assert.equal(pay(booking).id,payment.id);assert.equal(pr.findByReservationId(booking.id).filter(p=>p.payment_status==='paid').length,1);
  assert.ok(rr.findById(booking.id).confirmed_at);assert.equal(timeslots.findOne(slot.id).locked,true);
  pass('unpaid holds protect checkout; demo failure retries confirm one server-priced payment and lock the session');
  payment.payment_time='2000-01-01T00:00:00Z';finance.listPayouts('finance_admin');finance.settleAll({admin_id:'fin-test'},'finance_admin');assert.equal(payment.settled_at,undefined);
  fails(()=>finance.retryRelease(payment.id,'fin-test','finance_admin'),400);
  fails(()=>reservations.update(booking.id,{reservation_status:'completed'},'manager'),400);
  checkin.create({reservation_id:booking.id,staff_id:'rst-1234'});
  fails(()=>reservations.update(booking.id,{reservation_status:'completed'},'staff'),403);
  payment.payout_blocked=true;
  reservations.update(booking.id,{reservation_status:'completed'},'manager');assert.equal(payment.release_status,'blocked');assert.equal(payment.settled_at,undefined);
  payment.payout_blocked=false;process.env.DINETIME_DEMO_PAYOUT_FAILURE='1';
  finance.retryRelease(payment.id,'fin-test','finance_admin');assert.equal(payment.release_status,'failed');
  delete process.env.DINETIME_DEMO_PAYOUT_FAILURE;
  finance.retryRelease(payment.id,'fin-test','finance_admin');assert.ok(payment.settled_at);assert.equal(payment.release_status,'released');
  const attempts=payment.release_attempts.length,settled=payment.settled_at;
  finance.retryRelease(payment.id,'fin-test','finance_admin');reservations.update(booking.id,{reservation_status:'completed'},'manager');
  assert.equal(payment.release_attempts.length,attempts);assert.equal(payment.settled_at,settled);
  pass('seven-day release is removed; only manager completion enables release; blocked/failed retries are auditable and idempotent');
  const hold=book(tables[1]);rr.findById(hold.id).hold_expires_at=new Date(Date.now()-1000).toISOString();
  const {expireUnpaidHolds}=require(path.join(build,'common/utils/booking-lifecycle.util.js'));
  expireUnpaidHolds(rr,pr,ar);assert.equal(rr.findById(hold.id).reservation_status,'cancelled');assert.ok(rr.findById(hold.id).expired_at);
  assert.equal(ar.findByTableAndSlot(tables[1].id,slot.id).status,'available');fails(()=>pay(hold),400);
  const replacement=book(tables[1]);expireUnpaidHolds(rr,pr,ar);reservations.delete(hold.id);
  assert.equal(ar.findByTableAndSlot(tables[1].id,slot.id).status,'reserved');
  reservations.delete(replacement.id);
  pass('expiry frees only the old unpaid allocation; late payment and deleting an expired hold cannot damage a newer booking');
  const changed=book(tables[2]),changedPay=pay(changed);const deadline=rr.findById(changed.id).cancellation_deadline;
  reservations.modify(changed.id,{restaurant_id:restaurant.id,slot_id:next.id,table_ids:[tables[2].id],guest_count:2},'din-1234');
  assert.equal(rr.findById(changed.id).cancellation_deadline,deadline);
  const now=Date.now;Date.now=()=>Date.parse(deadline)+1;
  try{fails(()=>reservations.update(changed.id,{reservation_status:'cancelled'},'diner'),400);}finally{Date.now=now;}
  assert.equal(changedPay.payment_status,'paid');
  pass('moving a booking later never extends its original cancellation deadline or reopens a refund');
  for(const [i,decision] of ['release','refund_deposit','refund_full'].entries()) {
    const b=book(tables[i+3]),p=pr.findById(pay(b).id);
    fails(()=>reservations.update(b.id,{reservation_status:'no_show'},'staff'),400);
    const originalNow=Date.now;Date.now=()=>Date.parse(slot.slot_date+'T'+slot.start_time+'+05:30')+3600000;
    try{reservations.update(b.id,{reservation_status:'no_show'},'staff');}finally{Date.now=originalNow;}
    assert.equal(p.release_status,'review');finance.settleAll({admin_id:'fin-test'},'finance_admin');assert.equal(p.settled_at,undefined);
    rr.findById(b.id).no_show_at=new Date(Date.now()-90000000).toISOString();assert.equal(finance.listNoShows('finance_admin').find(r=>r.id===b.id).overdue,true);
    fails(()=>finance.decideNoShow(b.id,{decision,notes:'Verified',admin_id:'support'},'support_admin'),403);
    finance.decideNoShow(b.id,{decision,notes:'Verified evidence and booking terms',admin_id:'fin-test'},'finance_admin');
    const before=JSON.stringify(p);finance.decideNoShow(b.id,{decision,notes:'Retry',admin_id:'fin-test'},'finance_admin');assert.equal(JSON.stringify(p),before);
    fails(()=>finance.decideNoShow(b.id,{decision:decision==='release' ? 'refund_full':'release',notes:'Conflicting decision',admin_id:'fin-test'},'finance_admin'),400);
    if(decision==='release')assert.ok(p.settled_at);else assert.equal(p.refunded_amount,decision==='refund_full' ? p.amount:p.deposit_amount);
  }
  pass('no-shows wait for finance; all three decisions, 24-hour escalation, authorization, and conflicting decisions are verified');
  const layoutSlot=sr.findByRestaurantId(restaurant.id).find(s=>s.slot_date>next.slot_date && s.start_time===slot.start_time);
  const layout=[{table_id:tables[0].id,capacity:4,x:2,y:2,shape:'round'},{table_id:tables[1].id,capacity:3,x:3,y:2,shape:'square'}];
  timeslots.saveLayout(layoutSlot.id,{revision:layoutSlot.revision,tables:layout});
  assert.equal(sr.findById(layoutSlot.id).table_layout[0].shape,'round');
  fails(()=>timeslots.saveLayout(layoutSlot.id,{revision:layoutSlot.revision,tables:layout.map(t=>({...t,x:1,y:1}))}),400);
  pass('floor-plan positions and shapes persist; colliding tables are rejected atomically');
  const newDate=new Date(slot.slot_date+'T12:00:00Z');newDate.setUTCDate(newDate.getUTCDate()+20);
  const draft=timeslots.create({restaurant_id:restaurant.id,slot_date:newDate.toISOString().slice(0,10),start_time:'18:00',end_time:'20:00'});
  assert.equal(draft.published,false);fails(()=>book(tables[0],draft),400);
  timeslots.saveLayout(draft.id,{revision:draft.revision,tables:[{table_id:tables[0].id,capacity:2,x:0,y:0,shape:'round'}]});
  assert.equal(timeslots.findOne(draft.id).published,true);assert.ok(book(tables[0],timeslots.findOne(draft.id)).id);
  const {calculateReservationBill}=require(path.join(build,'common/utils/billing.util.js'));
  assert.equal(calculateReservationBill(2,0).restaurant_payout,0);
  assert.equal(calculateReservationBill(3,0.1).deposit_amount,0.3);
  const quoted=book(tables[1],next),quotedAmount=quoted.payment_quote.total_due;
  const oldRate=restaurant.reservation_fee_per_guest;restaurant.reservation_fee_per_guest=oldRate+50;
  try{assert.equal(pay(quoted).amount,quotedAmount);}finally{restaurant.reservation_fee_per_guest=oldRate;}
  pass('draft services cannot be booked before publish; checkout prices are frozen and zero/decimal deposits have valid payouts');
  console.log(`${checks} Phase 2 lifecycle checks passed.`);
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(app)await app.close();});
